    public function run(): void
    {
        foreach ($this->documents() as $key => $d) {
            DB::table('compliance_documents')->updateOrInsert(
                ['doc_key' => $key],
                [
                    'title' => $d['title'],
                    'mode' => $d['mode'],
                    'source' => $d['source'] ?? null,
                    'questions' => isset($d['questions']) ? json_encode($d['questions']) : null,
                    'owner_role' => $d['owner'] ?? null,
                    'ask' => $d['ask'] ?? null,
                    'advice' => $d['advice'] ?? null,
                    'updated_at' => now(),
                    'created_at' => now(),
                ]
            );
 
            // Map to ISO controls. verified=false until compliance:validate confirms them.
            foreach (($d['iso'] ?? []) as $ref) {
                DB::table('document_control_map')->updateOrInsert(
                    ['doc_key' => $key, 'framework_id' => self::ISO, 'control_ref' => $ref],
                    ['id' => (string) Str::uuid(), 'updated_at' => now(), 'created_at' => now()]
                );
            }
        }
 
        $this->command->info('Seeded ' . count($this->documents()) . ' documents.');
        $this->command->warn('Now run: php artisan compliance:validate');
    }
 
